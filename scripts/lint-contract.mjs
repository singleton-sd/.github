#!/usr/bin/env node
/**
 * Contract lint for reusable workflows and composite actions in this repo.
 *
 * Generate the lockfile:
 *   node scripts/lint-contract.mjs --write-lock
 * Verify (CI):
 *   node scripts/lint-contract.mjs
 */
import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const THIS_DIR = dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = join(THIS_DIR, "..");
const LOCK_REL = join(".github", "workflows", "actions.lock");
const SHA_USES = /^(.+)@([0-9a-fA-F]{40})$/;
const USES_LINE = /^[ \t]*uses:[ \t]*(\S+)(?:[ \t]*#[ \t]*(\S+))?[ \t]*$/;
const FORBIDDEN_PERM_STRINGS = new Set(["read-all", "write-all"]);
const INTERPOLATED_INPUT = /\$\{\{\s*(inputs|secrets)\./;

export const LOCK_HEADER = [
  "# Generated by: node scripts/lint-contract.mjs --write-lock",
  "# Verify with: node scripts/lint-contract.mjs",
  "# GitHub Actions lockfile schema v0.0.3. Also: gh actions-lock --verify-local",
].join("\n");

function isMain() {
  try {
    return import.meta.url === pathToFileURL(process.argv[1]).href;
  } catch {
    return false;
  }
}

function listFiles(dir, acc = []) {
  if (!existsSync(dir)) {
    return acc;
  }
  for (const ent of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, ent.name);
    if (ent.isDirectory()) {
      listFiles(path, acc);
    } else {
      acc.push(path);
    }
  }
  return acc;
}

export function workflowFiles(root) {
  const dir = join(root, ".github", "workflows");
  if (!existsSync(dir)) {
    return [];
  }
  return readdirSync(dir)
    .filter((name) => name.endsWith(".yml") || name.endsWith(".yaml"))
    .filter((name) => name !== "actions.lock")
    .map((name) => join(dir, name))
    .sort();
}

export function actionFiles(root) {
  return listFiles(join(root, "actions"))
    .filter((path) => path.endsWith("action.yml") || path.endsWith("action.yaml"))
    .sort();
}

export function loadYaml(text) {
  const proc = spawnSync(
    "python3",
    [
      "-c",
      "import json,sys,yaml; json.dump(yaml.safe_load(sys.stdin), sys.stdout)",
    ],
    { input: text, encoding: "utf8" },
  );
  if (proc.status !== 0) {
    const err = (proc.stderr || proc.stdout || "yaml parse failed").trim();
    throw new Error(err);
  }
  if (!proc.stdout) {
    return null;
  }
  return JSON.parse(proc.stdout);
}

function onBlock(loaded) {
  if (!loaded || typeof loaded !== "object") {
    return undefined;
  }
  if (Object.prototype.hasOwnProperty.call(loaded, "on")) {
    return loaded.on;
  }
  if (Object.prototype.hasOwnProperty.call(loaded, "true")) {
    return loaded.true;
  }
  return undefined;
}

function hasWorkflowCall(on) {
  if (on == null) {
    return false;
  }
  if (on === "workflow_call") {
    return true;
  }
  if (Array.isArray(on)) {
    return on.includes("workflow_call");
  }
  if (typeof on === "object") {
    return Object.prototype.hasOwnProperty.call(on, "workflow_call");
  }
  return false;
}

function walk(node, visit) {
  visit(node);
  if (Array.isArray(node)) {
    for (const item of node) {
      walk(item, visit);
    }
    return;
  }
  if (node && typeof node === "object") {
    for (const value of Object.values(node)) {
      walk(value, visit);
    }
  }
}

function isLocalUses(uses) {
  return uses.startsWith("./") || uses.startsWith("docker://");
}

function isSelfWorkflowName(name, rel) {
  const base = rel.split("/").pop() || "";
  if (base.startsWith("self-")) {
    return true;
  }
  return typeof name === "string" && name.startsWith("self-");
}

function emptyPermissions(value) {
  return value != null && typeof value === "object" && !Array.isArray(value) && Object.keys(value).length === 0;
}

function jobPermissionsOk(value) {
  if (value == null) {
    return false;
  }
  if (typeof value === "string") {
    return !FORBIDDEN_PERM_STRINGS.has(value);
  }
  return typeof value === "object" && !Array.isArray(value);
}

function concurrencyGroup(concurrency) {
  if (typeof concurrency === "string") {
    return concurrency;
  }
  if (concurrency && typeof concurrency === "object" && typeof concurrency.group === "string") {
    return concurrency.group;
  }
  return "";
}

function usesCheckoutWithoutRepository(step) {
  if (!step || typeof step !== "object") {
    return false;
  }
  const uses = step.uses;
  if (typeof uses !== "string" || !uses.startsWith("actions/checkout@")) {
    return false;
  }
  const withBlock = step.with;
  if (!withBlock || typeof withBlock !== "object") {
    return true;
  }
  return !Object.prototype.hasOwnProperty.call(withBlock, "repository");
}

function reusableChecksOutCaller(loaded) {
  const jobs = loaded.jobs;
  if (!jobs || typeof jobs !== "object") {
    return false;
  }
  for (const job of Object.values(jobs)) {
    const steps = job && job.steps;
    if (!Array.isArray(steps)) {
      continue;
    }
    if (steps.some(usesCheckoutWithoutRepository)) {
      return true;
    }
  }
  return false;
}

function workflowCallInputs(loaded) {
  const on = onBlock(loaded);
  if (!on || typeof on !== "object") {
    return {};
  }
  const call = on.workflow_call;
  if (!call || typeof call !== "object") {
    return {};
  }
  const inputs = call.inputs;
  return inputs && typeof inputs === "object" ? inputs : {};
}

function actionInputs(loaded) {
  const inputs = loaded.inputs;
  return inputs && typeof inputs === "object" ? inputs : {};
}

function findSecretsInherit(node, found) {
  if (Array.isArray(node)) {
    for (const item of node) {
      findSecretsInherit(item, found);
    }
    return;
  }
  if (!node || typeof node !== "object") {
    return;
  }
  if (node.secrets === "inherit") {
    found.push(true);
  }
  for (const value of Object.values(node)) {
    findSecretsInherit(value, found);
  }
}

function findInterpolatedRun(node, found) {
  if (Array.isArray(node)) {
    for (const item of node) {
      findInterpolatedRun(item, found);
    }
    return;
  }
  if (!node || typeof node !== "object") {
    return;
  }
  if (typeof node.run === "string" && INTERPOLATED_INPUT.test(node.run)) {
    found.push(node.run);
  }
  for (const value of Object.values(node)) {
    findInterpolatedRun(value, found);
  }
}

function hasJobSummary(raw) {
  return (
    raw.includes("GITHUB_STEP_SUMMARY") &&
    /workflow_ref/.test(raw) &&
    (/github\.sha/.test(raw) || /workflow_sha/.test(raw) || /HEAD_SHA/.test(raw))
  );
}

export function parseUsesLines(raw) {
  const pins = [];
  for (const line of raw.split(/\r?\n/)) {
    const match = USES_LINE.exec(line);
    if (!match) {
      continue;
    }
    pins.push({ uses: match[1], version: match[2] || "" });
  }
  return pins;
}

export function lockKeyForPin(pin) {
  const match = SHA_USES.exec(pin.uses);
  if (!match) {
    return pin.uses.toLowerCase();
  }
  return `${match[1].toLowerCase()}@${match[2].toLowerCase()}`;
}

function yamlQuote(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function commitSha(commit) {
  if (typeof commit !== "string") {
    return "";
  }
  return commit.startsWith("sha1-") ? commit.slice("sha1-".length).toLowerCase() : commit.toLowerCase();
}

export function formatLock(pins, existingText = "") {
  let existingDeps = {};
  let existingWorkflows = {};
  if (existingText) {
    try {
      const loaded = loadYaml(existingText);
      if (loaded && typeof loaded === "object") {
        if (loaded.dependencies && typeof loaded.dependencies === "object") {
          existingDeps = loaded.dependencies;
        }
        if (loaded.workflows && typeof loaded.workflows === "object") {
          existingWorkflows = loaded.workflows;
        }
      }
    } catch {
      existingDeps = {};
    }
  }
  const dependencies = { ...existingDeps };
  const workflowSets = {};
  for (const [rel, list] of Object.entries(existingWorkflows)) {
    workflowSets[rel] = new Set(Array.isArray(list) ? list : []);
  }
  for (const pin of pins) {
    const key = lockKeyForPin(pin);
    const match = SHA_USES.exec(pin.uses);
    const sha = match ? match[2].toLowerCase() : "";
    const prev = dependencies[key] && typeof dependencies[key] === "object" ? dependencies[key] : {};
    dependencies[key] = {
      ...prev,
      ref: pin.version || prev.ref || sha,
      commit: `sha1-${sha}`,
    };
    const rel = (pin.from || "").replace(/\\/g, "/");
    if (rel.startsWith(".github/workflows/") && rel.endsWith(".yml")) {
      if (!workflowSets[rel]) {
        workflowSets[rel] = new Set();
      }
      // GitHub rejects duplicate keys in a workflow's pin list.
      workflowSets[rel].add(key);
    }
  }
  const workflowNames = [...new Set([
    ...Object.keys(workflowSets),
    ...pins
      .map((pin) => (pin.from || "").replace(/\\/g, "/"))
      .filter((rel) => rel.startsWith(".github/workflows/") && rel.endsWith(".yml")),
  ])].sort();
  let body = `${LOCK_HEADER}\nversion: 'v0.0.3'\nworkflows:\n`;
  for (const rel of workflowNames) {
    const keys = [...(workflowSets[rel] || [])].sort();
    body += `    ${yamlQuote(rel)}:\n`;
    if (keys.length === 0) {
      body += "        []\n";
      continue;
    }
    for (const key of keys) {
      body += `        - ${yamlQuote(key)}\n`;
    }
  }
  body += "dependencies:\n";
  for (const key of Object.keys(dependencies).sort()) {
    const meta = dependencies[key] && typeof dependencies[key] === "object" ? dependencies[key] : {};
    body += `    ${yamlQuote(key)}:\n`;
    body += `        ref: ${yamlQuote(meta.ref || "")}\n`;
    body += `        commit: ${yamlQuote(meta.commit || "")}\n`;
    if (meta.owner_id != null) {
      body += `        owner_id: ${meta.owner_id}\n`;
    }
    if (meta.repo_id != null) {
      body += `        repo_id: ${meta.repo_id}\n`;
    }
    if (Array.isArray(meta.uses) && meta.uses.length > 0) {
      body += "        uses:\n";
      for (const child of meta.uses) {
        body += `            - ${yamlQuote(child)}\n`;
      }
    }
  }
  return body;
}

export function parseLock(text) {
  const loaded = loadYaml(text);
  if (!loaded || typeof loaded !== "object") {
    throw new Error("actions.lock: expected a mapping");
  }
  if (loaded.version !== "v0.0.3") {
    throw new Error("actions.lock: expected version: v0.0.3");
  }
  const dependencies = loaded.dependencies;
  if (!dependencies || typeof dependencies !== "object" || Array.isArray(dependencies)) {
    throw new Error("actions.lock: expected dependencies: mapping");
  }
  return {
    version: loaded.version,
    workflows: loaded.workflows && typeof loaded.workflows === "object" ? loaded.workflows : {},
    dependencies,
  };
}

export function duplicateLockKeys(workflows) {
  const errors = [];
  if (!workflows || typeof workflows !== "object") {
    return errors;
  }
  for (const [rel, list] of Object.entries(workflows)) {
    if (!Array.isArray(list)) {
      continue;
    }
    const seen = new Set();
    for (const key of list) {
      if (seen.has(key)) {
        errors.push(
          `${LOCK_REL}: duplicate dependency key for workflow ${JSON.stringify(rel)}: ${JSON.stringify(key)}`,
        );
      }
      seen.add(key);
    }
  }
  return errors;
}

function selfTestCallers(root) {
  const path = join(root, ".github", "workflows", "self-test.yml");
  if (!existsSync(path)) {
    return "";
  }
  return readFileSync(path, "utf8");
}

export function collectThirdPartyPins(root) {
  const files = [...workflowFiles(root), ...actionFiles(root)];
  const pins = [];
  const errors = [];
  for (const file of files) {
    const rel = relative(root, file);
    const raw = readFileSync(file, "utf8");
    for (const pin of parseUsesLines(raw)) {
      if (isLocalUses(pin.uses)) {
        continue;
      }
      const sha = SHA_USES.exec(pin.uses);
      if (!sha) {
        errors.push(`${rel}: unpinned uses: ${pin.uses}`);
        continue;
      }
      if (!pin.version) {
        errors.push(`${rel}: uses: ${pin.uses} is missing a # vX.Y.Z comment`);
        continue;
      }
      pins.push({ ...pin, from: rel });
    }
  }
  return { pins, errors };
}

function lintReusableWorkflow(rel, raw, loaded, root, errors) {
  if (!emptyPermissions(loaded.permissions)) {
    errors.push(`${rel}: reusable workflows must set top-level permissions: {}`);
  }
  const jobs = loaded.jobs;
  if (!jobs || typeof jobs !== "object") {
    errors.push(`${rel}: expected jobs:`);
  } else {
    for (const [id, job] of Object.entries(jobs)) {
      if (!jobPermissionsOk(job.permissions)) {
        errors.push(`${rel}: job '${id}' must declare minimal permissions`);
      }
    }
  }
  const inherit = [];
  findSecretsInherit(loaded, inherit);
  if (inherit.length > 0) {
    errors.push(`${rel}: secrets: inherit is forbidden`);
  }
  const interpolated = [];
  findInterpolatedRun(loaded, interpolated);
  if (interpolated.length > 0) {
    errors.push(`${rel}: pass inputs through env:; do not interpolate inputs or secrets into run:`);
  }
  const group = concurrencyGroup(loaded.concurrency);
  if (group.includes("github.workflow")) {
    errors.push(`${rel}: concurrency groups must not use github.workflow`);
  }
  const inputs = workflowCallInputs(loaded);
  for (const [name, spec] of Object.entries(inputs)) {
    if (!spec || typeof spec !== "object") {
      errors.push(`${rel}: input '${name}' must be a mapping`);
      continue;
    }
    if (typeof spec.description !== "string" || spec.description.trim() === "") {
      errors.push(`${rel}: input '${name}' must have a description`);
    }
    if (typeof spec.type !== "string" || spec.type.trim() === "") {
      errors.push(`${rel}: input '${name}' must have a type`);
    }
    const required = spec.required === true;
    if (!required && !Object.prototype.hasOwnProperty.call(spec, "default")) {
      errors.push(`${rel}: input '${name}' must have a default`);
    }
  }
  if (reusableChecksOutCaller(loaded) && !Object.prototype.hasOwnProperty.call(inputs, "working_directory")) {
    errors.push(`${rel}: reusable workflows that check out the caller must declare working_directory`);
  }
  if (!hasJobSummary(raw)) {
    errors.push(`${rel}: job summary must include the workflow ref and SHA`);
  }
  const selfTest = selfTestCallers(root);
  const localUses = `uses: ./${rel.replace(/\\/g, "/")}`;
  if (!selfTest.includes(localUses)) {
    errors.push(`${rel}: self-test.yml must call this workflow via ${localUses}`);
  }
  const base = rel.split("/").pop() || "";
  if (base.includes("deploy")) {
    if (!Object.prototype.hasOwnProperty.call(inputs, "dry_run")) {
      errors.push(`${rel}: deploy-type workflows must declare a dry_run input`);
    }
  }
}

function lintCompositeAction(rel, raw, loaded, errors) {
  const inherit = [];
  findSecretsInherit(loaded, inherit);
  if (inherit.length > 0) {
    errors.push(`${rel}: secrets: inherit is forbidden`);
  }
  const interpolated = [];
  findInterpolatedRun(loaded, interpolated);
  if (interpolated.length > 0) {
    errors.push(`${rel}: pass inputs through env:; do not interpolate inputs or secrets into run:`);
  }
  const inputs = actionInputs(loaded);
  for (const [name, spec] of Object.entries(inputs)) {
    if (!spec || typeof spec !== "object") {
      errors.push(`${rel}: input '${name}' must be a mapping`);
      continue;
    }
    if (typeof spec.description !== "string" || spec.description.trim() === "") {
      errors.push(`${rel}: input '${name}' must have a description`);
    }
    const required = spec.required === true;
    if (!required && !Object.prototype.hasOwnProperty.call(spec, "default")) {
      errors.push(`${rel}: input '${name}' must have a default`);
    }
  }
  if (!hasJobSummary(raw)) {
    errors.push(`${rel}: job summary must include the workflow ref and SHA`);
  }
}

function lintSelfWorkflow(rel, loaded, errors) {
  if (!emptyPermissions(loaded.permissions)) {
    errors.push(`${rel}: self-* workflows must set top-level permissions: {}`);
  }
  const jobs = loaded.jobs;
  if (!jobs || typeof jobs !== "object") {
    errors.push(`${rel}: expected jobs:`);
  } else {
    for (const [id, job] of Object.entries(jobs)) {
      if (!jobPermissionsOk(job.permissions)) {
        errors.push(`${rel}: job '${id}' must declare minimal permissions`);
      }
    }
  }
  const inherit = [];
  findSecretsInherit(loaded, inherit);
  if (inherit.length > 0) {
    errors.push(`${rel}: secrets: inherit is forbidden`);
  }
  const interpolated = [];
  findInterpolatedRun(loaded, interpolated);
  if (interpolated.length > 0) {
    errors.push(`${rel}: pass inputs through env:; do not interpolate inputs or secrets into run:`);
  }
  const group = concurrencyGroup(loaded.concurrency);
  if (group.includes("github.workflow")) {
    errors.push(`${rel}: concurrency groups must not use github.workflow`);
  }
}

export function lintRepo(root, options = {}) {
  const errors = [];
  const files = [...workflowFiles(root), ...actionFiles(root)];
  if (files.length === 0) {
    errors.push("no workflows or composite actions to lint");
  }
  for (const file of files) {
    const rel = relative(root, file).replace(/\\/g, "/");
    const raw = readFileSync(file, "utf8");
    let loaded;
    try {
      loaded = loadYaml(raw);
    } catch (err) {
      errors.push(`${rel}: YAML parse error: ${err.message}`);
      continue;
    }
    if (!loaded || typeof loaded !== "object") {
      errors.push(`${rel}: expected a mapping`);
      continue;
    }
    const reusable = hasWorkflowCall(onBlock(loaded));
    const composite = loaded.runs && loaded.runs.using === "composite";
    const selfWf = isSelfWorkflowName(loaded.name, rel);
    if (reusable) {
      lintReusableWorkflow(rel, raw, loaded, root, errors);
    } else if (composite) {
      lintCompositeAction(rel, raw, loaded, errors);
    } else if (selfWf) {
      lintSelfWorkflow(rel, loaded, errors);
    }
  }

  const collected = collectThirdPartyPins(root);
  errors.push(...collected.errors);
  const lockPath = join(root, LOCK_REL);
  const existingText = existsSync(lockPath) ? readFileSync(lockPath, "utf8") : "";
  const expectedLock = formatLock(collected.pins, existingText);
  if (options.writeLock) {
    mkdirSync(dirname(lockPath), { recursive: true });
    writeFileSync(lockPath, expectedLock);
  }
  if (!existsSync(lockPath)) {
    errors.push(`${LOCK_REL}: missing; generate with node scripts/lint-contract.mjs --write-lock`);
  } else {
    try {
      const lock = parseLock(readFileSync(lockPath, "utf8"));
      errors.push(...duplicateLockKeys(lock.workflows));
      for (const pin of collected.pins) {
        const key = lockKeyForPin(pin);
        const dep = lock.dependencies[key];
        if (!dep || typeof dep !== "object") {
          errors.push(`${LOCK_REL}: missing ${key}`);
          continue;
        }
        const match = SHA_USES.exec(pin.uses);
        const sha = match ? match[2].toLowerCase() : "";
        if (commitSha(dep.commit) !== sha) {
          errors.push(`${LOCK_REL}: ${key} commit does not match workflow SHA`);
        }
        if (pin.version && dep.ref && dep.ref !== pin.version) {
          errors.push(`${LOCK_REL}: ${key} ref ${dep.ref} does not match comment ${pin.version}`);
        }
      }
    } catch (err) {
      errors.push(`${LOCK_REL}: ${err.message}`);
    }
  }

  return { errors, lock: expectedLock, pins: collected.pins };
}

function parseArgs(argv) {
  const args = { writeLock: false, root: DEFAULT_ROOT };
  const rest = [];
  for (const arg of argv) {
    if (arg === "--write-lock") {
      args.writeLock = true;
    } else if (arg === "--help" || arg === "-h") {
      args.help = true;
    } else {
      rest.push(arg);
    }
  }
  if (rest[0]) {
    args.root = rest[0];
  }
  return args;
}

function main(argv = process.argv.slice(2)) {
  const args = parseArgs(argv);
  if (args.help) {
    process.stdout.write(
      "Usage: node scripts/lint-contract.mjs [--write-lock] [root]\n",
    );
    return 0;
  }
  const result = lintRepo(args.root, { writeLock: args.writeLock });
  if (result.errors.length > 0) {
    for (const error of result.errors) {
      process.stderr.write(`::error::${error}\n`);
      process.stderr.write(`${error}\n`);
    }
    return 1;
  }
  const pinCount = result.pins.length;
  process.stdout.write(
    `lint-contract: passed (${pinCount} third-party pin(s), lock ${args.writeLock ? "written" : "verified"})\n`,
  );
  return 0;
}

if (isMain()) {
  process.exit(main());
}
